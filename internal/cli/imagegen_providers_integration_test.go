package cli

import (
	"bytes"
	"context"
	"encoding/base64"
	"encoding/json"
	"fmt"
	"net/http"
	"net/http/httptest"
	"os"
	"os/exec"
	"path/filepath"
	"testing"
	"time"

	"github.com/modelcontextprotocol/go-sdk/mcp"

	"satchel/internal/config"
)

func TestSatchelStdioOpenRouterGenerateImage(t *testing.T) {
	png := []byte("\x89PNG\r\n\x1a\n" + "openrouter-stdio")
	resultURL := "data:image/png;base64," + base64.StdEncoding.EncodeToString(png)
	// The default test is fully local. Setting this opt-in variable exercises
	// the real public HTTP downloader instead of the inline data-URL path.
	publicDownload := os.Getenv("SATCHEL_TEST_PUBLIC_IMAGE_URL")
	if publicDownload != "" {
		resultURL = publicDownload
	}
	provider := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if r.URL.Path != "/api/v1/images" || r.Header.Get("Authorization") != "Bearer openrouter-key" {
			t.Errorf("unexpected OpenRouter request: %s", r.URL.Path)
		}
		var body map[string]any
		if err := json.NewDecoder(r.Body).Decode(&body); err != nil {
			t.Error(err)
		}
		if body["model"] != "image-test" || body["prompt"] != "openrouter stdio" {
			t.Errorf("payload = %#v", body)
		}
		w.Header().Set("Content-Type", "application/json")
		fmt.Fprintf(w, `{"data":[{"url":%q}]}`, resultURL)
	}))
	defer provider.Close()
	root := t.TempDir()
	configPath := filepath.Join(root, "config.json")
	t.Setenv("SATCHEL_CONFIG", configPath)
	cfg := config.Default()
	cfg.Tools.ImageAsk = false
	cfg.Tools.WebSearch = false
	cfg.Tools.WebFetch = false
	cfg.Image.Default = config.ImageDefault{Provider: "openrouter", Model: "image-test"}
	cfg.Image.OutputDir = filepath.Join(root, "images")
	cfg.Image.Providers["openrouter"] = config.ImageProvider{API: "openrouter", BaseURL: provider.URL + "/api/v1", APIKey: "openrouter-key"}
	if err := config.Save(cfg); err != nil {
		t.Fatal(err)
	}
	binary := filepath.Join(root, "satchel")
	build := exec.Command("go", "build", "-o", binary, "./cmd/satchel")
	build.Dir = "../.."
	if output, err := build.CombinedOutput(); err != nil {
		t.Fatalf("build satchel: %v\n%s", err, output)
	}
	command := exec.Command(binary, "mcp")
	command.Env = append(os.Environ(), "SATCHEL_CONFIG="+configPath)
	var stderr bytes.Buffer
	command.Stderr = &stderr
	client := mcp.NewClient(&mcp.Implementation{Name: "satchel-openrouter-e2e", Version: "0"}, nil)
	ctx, cancel := context.WithTimeout(context.Background(), 20*time.Second)
	defer cancel()
	session, err := client.Connect(ctx, &mcp.CommandTransport{Command: command}, nil)
	if err != nil {
		t.Fatalf("connect stdio: %v; stderr=%s", err, stderr.String())
	}
	result, err := session.CallTool(ctx, &mcp.CallToolParams{Name: "generate_image", Arguments: map[string]any{"prompt": "openrouter stdio"}})
	if err != nil || result.IsError {
		t.Fatalf("generate_image = %+v, %v", result, err)
	}
	files, err := filepath.Glob(filepath.Join(cfg.Image.OutputDir, "*.png"))
	if err != nil || len(files) != 1 {
		t.Fatalf("generated files = %v, %v; result=%s", files, err, mcpText(result))
	}
	data, err := os.ReadFile(files[0])
	if publicDownload == "" && (err != nil || !bytes.Equal(data, png)) {
		t.Fatalf("generated bytes = %x, %v", data, err)
	}
	if publicDownload != "" && (err != nil || len(data) < 8 || !bytes.Equal(data[:8], []byte("\x89PNG\r\n\x1a\n"))) {
		t.Fatalf("downloaded file is not a PNG: %d bytes, %v", len(data), err)
	}
	if err := session.Close(); err != nil {
		t.Fatal(err)
	}
	if stderr.String() != "" {
		t.Fatalf("unexpected MCP stderr: %s", stderr.String())
	}
}
